class RecordingDispatcher implements INotificationDispatcher {
  public dispatched: Array<{
    event: string;
    params: any;
  }> = [];

  public failWith?: { error: string; deliveryStatus?: any };
  public delayMs: number = 0;

  async dispatch(event: string, params: any): Promise<DispatchResult> {
    if (this.delayMs > 0) {
      await new Promise((r) => setTimeout(r, this.delayMs));
    }

    if (this.failWith) {
      return {
        success: false,
        deliveryStatus: this.failWith.deliveryStatus || 'retryable_fail',
        error: this.failWith.error,
      };
    }

    this.dispatched.push({ event, params });
    return {
      success: true,
      deliveryStatus: 'delivered',
      messageId: `<mock-${crypto.randomUUID()}@synq.io>`,
    };
  }
}

