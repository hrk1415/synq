    const secondBatch = await processor.processBatch();
    assert.equal(secondBatch.claimedCount, 0, 'Quarantined item must not be re-processed');
    assert.equal(dispatcher.dispatched.length, 1, 'No duplicate email dispatched');

    // Case B: Critical quarantine failure logging
